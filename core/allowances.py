def calc_min_allowance_diameter(
    Rz: float,
    Tdef: float,
    rho: float,
    epsilon: float,
    arithmetic: bool = False,
) -> float:
    """
    Минимальный припуск на ДИАМЕТР для тел вращения (мкм).

    arithmetic=False → геометрическое суммирование rho и epsilon:
        2z_min = 2 * (Rz + Tdef + sqrt(rho² + epsilon²))

    arithmetic=True → арифметическое (худший случай):
        2z_min = 2 * (Rz + Tdef + rho + epsilon)
    """
    if arithmetic:
        return 2.0 * (Rz + Tdef + rho + epsilon)
    else:
        import math
        return 2.0 * (Rz + Tdef + math.sqrt(rho ** 2 + epsilon ** 2))


def calc_min_allowance_flat(
    Rz: float,
    Tdef: float,
    rho: float,
    epsilon: float,
) -> float:
    """
    Минимальный припуск при ОДНОСТОРОННЕЙ обработке (плоские поверхности), мкм.
    z_min = Rz + Tdef + rho + epsilon
    """
    return Rz + Tdef + rho + epsilon


def get_prev_errors(operation_key: str):
    """
    Возвращает (Rz, Tdef, rho, delta_sum) из таблицы 5.2.
    """
    return PREV_OPERATION_ERRORS.get(operation_key)


def get_fixture_error(fixture_key: str) -> Optional[float]:
    """
    Возвращает εi из таблицы 5.3.
    """
    return FIXTURE_ERRORS.get(fixture_key)


def get_surface_quality(method_key: str):
    """
    Возвращает (Rz, Tdef) из таблицы 5.1.
    """
    return SURFACE_QUALITY.get(method_key)


def get_thread_shank(thread_d_mm: float):
    """
    Возвращает (d_max, tolerance) для стержня под метрическую резьбу.
    """
    return THREAD_SHANK_DIAMETERS.get(thread_d_mm)


