def main():
    if not os.path.exists(DB_PATH):
        print("❌ Не найден drawing_db.json рядом со скриптом:", DB_PATH)
        return

    # бэкап
    backup = DB_PATH.replace(".json", ".backup.json")
    shutil.copy(DB_PATH, backup)
    print("Резервная копия:", backup)

    db = json.load(open(DB_PATH, encoding="utf-8"))
    filled = 0
    already = 0
    no_data = 0

    def norm(s):
        return (s or "").replace(" ", "").lower()

    cm_norm = {norm(k): v for k, v in CLEAN_MASS.items()}

    for r in db:
        dno = norm(r.get("drawing_no", ""))
        if dno in cm_norm:
            r["mass_clean_kg"] = cm_norm[dno]
            filled += 1
        else:
            # ставим null, если поля ещё нет (для единообразия схемы)
            if "mass_clean_kg" not in r:
                r["mass_clean_kg"] = None
                no_data += 1
            else:
                already += 1

    json.dump(db, open(DB_PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    print(f"✅ Готово. Всего записей: {len(db)}")
    print(f"   • заполнено чистовой массой: {filled}")
    print(f"   • без данных (null): {no_data}")
    if already:
        print(f"   • уже имели поле: {already}")
    print("Если что-то не так — верни backup-файл.")


if __name__ == "__main__":
    main()
